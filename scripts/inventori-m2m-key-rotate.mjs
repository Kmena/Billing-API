/**
 * Inventori M2M Key Rotation — stores secret in .env.local (SecretProvider for local dev).
 * SAFETY: NEVER prints secret to stdout. Writes only to .env.local (gitignored).
 */
import { readFileSync, writeFileSync } from 'fs';
import { PrismaClient } from '@prisma/client';

const envFile = readFileSync('.env.local', 'utf8');
for (const line of envFile.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const eqIdx = trimmed.indexOf('=');
  if (eqIdx < 0) continue;
  const key = trimmed.slice(0, eqIdx).trim();
  const val = trimmed.slice(eqIdx + 1).trim();
  if (key && !process.env[key]) process.env[key] = val;
}

const BASE_URL = `http://localhost:${process.env.PORT ?? 3000}/api/v1`;
const TENANT_ID  = process.env.INVENTORI_SANDBOX_TENANT_ID;
const COMPANY_ID = process.env.INVENTORI_SANDBOX_COMPANY_ID;
const ADMIN_EMAIL    = 'admin@inventori-sandbox.billing';
const ADMIN_PASSWORD = 'Admin@Billing2026!';

const REQUIRED_SCOPES = [
  'taxpayers:read', 'cabys:read', 'exchange-rates:read',
  'fiscal-onboarding:read', 'fiscal-onboarding:write',
  'invoices:read', 'invoices:write', 'tickets:read', 'tickets:write',
];

const prisma = new PrismaClient();

async function apiPost(path, body, token) {
  const res = await fetch(`${BASE_URL}${path}`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
    body: JSON.stringify(body),
  });
  const json = await res.json();
  if (!res.ok) throw Object.assign(new Error(`POST ${path} → ${res.status}`), { body: json });
  return json;
}
async function apiGet(path, token) {
  const res = await fetch(`${BASE_URL}${path}`, {
    method: 'GET',
    headers: { Authorization: `Bearer ${token}` },
  });
  return res.json();
}
async function apiDelete(path, token) {
  const res = await fetch(`${BASE_URL}${path}`, { method: 'DELETE', headers: { Authorization: `Bearer ${token}` } });
  return res.status;
}

async function main() {
  // Login
  const auth = await apiPost('/auth/login', { tenantId: TENANT_ID, email: ADMIN_EMAIL, password: ADMIN_PASSWORD });
  const JWT = auth.accessToken;
  console.log('[OK] Authenticated.');

  // Revoke existing keys that have 'inventori' in name
  const existingKeys = await apiGet('/api-keys', JWT);
  for (const k of existingKeys) {
    if (k.name?.toLowerCase().includes('inventori')) {
      const status = await apiDelete(`/api-keys/${k.id}`, JWT);
      console.log(`[OK] Revoked existing key ${k.id} (${k.name}) → status ${status}`);
    }
  }

  // Create new key
  const newKey = await apiPost('/api-keys', {
    name: 'Inventori SANDBOX M2M',
    environment: 'TEST',
    scopes: REQUIRED_SCOPES,
  }, JWT);

  console.log(`[OK] New M2M key created: id=${newKey.id} prefix=${newKey.keyPrefix}`);
  console.log(`[OK] Scopes: ${JSON.stringify(newKey.scopes)}`);

  // Store secret in .env.local (local SecretProvider)
  // SECURITY: secret is ONLY written to .env.local (gitignored), never to stdout.
  let envContent = readFileSync('.env.local', 'utf8');
  const keyLine = `INVENTORI_M2M_API_KEY=${newKey.secret}`;
  const keyComment = '# Inventori SANDBOX M2M API key — generated by bootstrap. Deliver securely to Inventori.';

  if (envContent.includes('INVENTORI_M2M_API_KEY=')) {
    envContent = envContent.replace(/INVENTORI_M2M_API_KEY=.*/, keyLine);
  } else {
    envContent += `\n${keyComment}\n${keyLine}\nINVENTORI_M2M_API_KEY_ID=${newKey.id}\nINVENTORI_M2M_API_KEY_PREFIX=${newKey.keyPrefix}\n`;
  }
  writeFileSync('.env.local', envContent, 'utf8');
  console.log('[OK] Secret stored in .env.local (gitignored). NEVER printed.');
  console.log(`[INFO] Key reference: id=${newKey.id} prefix=${newKey.keyPrefix}`);

  // Verify it works
  const smokeRes = await fetch(`${BASE_URL}/companies/${COMPANY_ID}/fiscal-onboarding/status`, {
    headers: { 'X-API-Key': newKey.secret },
  });
  const smokeBody = await smokeRes.json();
  if (smokeRes.ok) {
    console.log(`[OK] Smoke test: M2M key works → status=${smokeBody.haciendaVerificationStatus}`);
  } else {
    console.log(`[WARN] Smoke test: ${smokeRes.status} ${JSON.stringify(smokeBody)}`);
  }

  // Smoke test 2: activities
  const actRes = await fetch(`${BASE_URL}/companies/${COMPANY_ID}/fiscal-onboarding/activities`, {
    headers: { 'X-API-Key': newKey.secret },
  });
  const actBody = await actRes.json();
  if (actRes.ok) {
    console.log(`[OK] Smoke test 2: activities → ${actBody.length} activities`);
    for (const a of actBody) console.log(`  activity: code=${a.code} status=${a.haciendaStatus} kind=${a.haciendaKind}`);
  } else {
    console.log(`[WARN] Smoke test 2: ${actRes.status}`);
  }

  console.log('\n[FINAL]');
  console.log('  Key ID:       ', newKey.id);
  console.log('  Key prefix:   ', newKey.keyPrefix);
  console.log('  Scopes:       ', JSON.stringify(newKey.scopes));
  console.log('  Secret stored: .env.local (gitignored)');
  console.log('  Secret value:  [REDACTED — see .env.local on this machine only]');
}

main().catch(e => { console.error(e.message, e.body); process.exit(1); }).finally(() => prisma.$disconnect());
